<template>
  <Card
    :cardClass="'height-equal'"
    :headerTitle="'Custom Positioned Dialog'"
    :border="true"
    :padding="false"
  >
    <template #header5>
      <p class="f-m-light mt-1">
        Use <code>Swal.fire</code> to display a success message at the top-right corner of the
        screen with an auto-close timer.
      </p>
    </template>

    <button class="btn btn-warning sweet-19" type="button" @click="open()">Click it!</button>
  </Card>
</template>

<script setup lang="ts">
import { defineAsyncComponent } from 'vue'

import Swal from 'sweetalert2'

const Card = defineAsyncComponent(() => import('@/components/shared/card/Card.vue'))

function open() {
  Swal.fire({
    position: 'top-end',
    icon: 'success',
    title: 'Your work has been saved',
    showConfirmButton: false,
    timer: 1500,
  })
}
</script>
