export function isDemoHospitalId(id: unknown): boolean {
  return Number(id) === DEMO_HOSPITAL_ID;
}

export function demoHospitalMatchesSearch(search?: string): boolean {
  const query = String(search ?? "").trim().toLocaleLowerCase("id-ID");
  if (!query) return true;
  return [
    DEMO_HOSPITAL.name,
    DEMO_HOSPITAL.email,
    DEMO_HOSPITAL.city,
    DEMO_HOSPITAL.province,
    DEMO_HOSPITAL.hospitalClass,
    DEMO_HOSPITAL.hospitalType,
  ].some((value) => value.toLocaleLowerCase("id-ID").includes(query));
}

export function isDemoProjectId(id: unknown): boolean {
  const normalized = Number(id);
  return normalized > DEMO_PROJECT_ID_START && normalized <= DEMO_PROJECT_ID_START + 5;
}
